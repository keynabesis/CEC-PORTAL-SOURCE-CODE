-- MySQL 8.0.16+ (8.4 recommended). Run once in MySQL Workbench.
-- No demonstration accounts or passwords are inserted into the live database.
CREATE DATABASE IF NOT EXISTS cec_portal CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE cec_portal;
CREATE TABLE IF NOT EXISTS users (
 id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 email VARCHAR(254) NOT NULL UNIQUE,
 school_id VARCHAR(40) NOT NULL UNIQUE,
 role ENUM('student','teacher') NOT NULL DEFAULT 'student',
 data JSON NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (JSON_TYPE(data)='OBJECT')
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 user_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 expires BIGINT UNSIGNED NOT NULL,
 INDEX (expires), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS academic_records (
 id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 data JSON NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CHECK (JSON_TYPE(data)='OBJECT'),
 FOREIGN KEY (id) REFERENCES users(id)
